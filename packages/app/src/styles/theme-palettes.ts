// Community theme palettes, ported from each project's published colors.
//
// Each entry maps a palette onto the app's surface ramp: surface0 is the page,
// surface1/2 step up for cards and controls, surface3/4 are borders and rings,
// and surfaceSidebar sits a step darker (dark) or tinted (light). Status and diff
// colors stay on the app-wide bands in theme.ts; only surfaces, text, accent and
// the terminal ANSI set come from the palette.
//
// Type-only import: theme.ts builds these, so a value import would be circular.
